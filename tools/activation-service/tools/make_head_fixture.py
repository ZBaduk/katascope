"""Writes the TypeScript head fixture from the numpy reference implementation.

The core spec needs weights and an expected output it did not compute itself.
Generating both here makes `support.head_reference` the oracle for the
TypeScript port -- and that reference is in turn pinned to the real model by
`test_head_golden`, so the chain ends at the network rather than at an opinion.

Deliberately tiny and synthetic: 6 trunk channels, 4 head channels, a 5x4 board
inside a 5x5 extent. Small enough to read, and rectangular-inside-larger so the
board mask and the pooled branch's board-size term are both exercised. Real
weights would make a huge fixture that tests the same arithmetic.

    .venv/bin/python tools/make_head_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tests"))

from support.head_reference import policy_softmax, run_heads  # noqa: E402

OUT = ROOT.parents[1] / "packages/core/fixtures/heads/tiny-head.json"

CHANNELS = 6
C_P1 = 4
C_G1 = 4
C_V1 = 4
POLICY_OUTPUTS = 6
POS_LEN = 5
BOARD_X = 5
BOARD_Y = 4


class _Weights:
    """Mimics the extractor's `HeadWeights` closely enough for the reference."""

    def __init__(self, tensors, shapes):
        self.tensors = tensors
        self.shapes = shapes
        self.version = 14
        self.activation = "mish"
        self.trunk_channels = CHANNELS
        self.pos_len = POS_LEN
        self.trunk_final_scale = 1.0 / np.sqrt(19.0)


def main() -> None:
    rng = np.random.default_rng(20_260_915)

    def draw(*shape):
        # Spread around zero and away from it, so no activation sits in a
        # region where a wrong one would look the same as the right one.
        return rng.normal(0.0, 0.7, size=shape)

    shapes = {
        "trunkfinal.beta": [CHANNELS],
        "policy.conv1p": [C_P1, CHANNELS],
        "policy.conv1g": [C_G1, CHANNELS],
        "policy.biasg": [C_G1],
        "policy.linear_g": [C_P1, 3 * C_G1],
        "policy.linear_pass": [POLICY_OUTPUTS, 3 * C_G1],
        "policy.bias2": [C_P1],
        "policy.conv2p": [POLICY_OUTPUTS, C_P1],
        "value.conv1": [C_V1, CHANNELS],
        "value.bias1": [C_V1],
        "value.conv_ownership": [1, C_V1],
    }
    tensors = {name: draw(*shape) for name, shape in shapes.items()}
    weights = _Weights({k: v.reshape(-1) for k, v in tensors.items()}, shapes)

    trunk = draw(CHANNELS, POS_LEN, POS_LEN)
    head_input, logits, pass_logit, ownership = run_heads(weights, trunk, BOARD_X, BOARD_Y)
    probs = policy_softmax(logits, pass_logit)

    # A reduction too, so the fixture pins the masking rule and not only the
    # forward pass: channels 0 and 3 kept, the rest zeroed at the head input.
    selected = [0, 3]
    reduced_input = head_input.copy()
    for c in range(CHANNELS):
        if c not in selected:
            reduced_input[c] = 0.0
    from support.head_reference import ownership_head, policy_head, board_mask

    mask = board_mask(POS_LEN, BOARD_X, BOARD_Y).astype(np.float64)
    mask_sum = float(BOARD_X * BOARD_Y)
    unpacked = {k: np.asarray(v, dtype=np.float64).reshape(shapes[k]) for k, v in weights.tensors.items()}
    red_logits, red_pass = policy_head(reduced_input, unpacked, mask, mask_sum, "mish")
    red_own = ownership_head(reduced_input, unpacked, mask, "mish")

    fixture = {
        "comment": (
            "Generated by tools/make_head_fixture.py from the numpy reference "
            "implementation, which test_head_golden pins to the real model. "
            "Do not hand-edit; regenerate."
        ),
        "version": weights.version,
        "activation": weights.activation,
        "trunkChannels": CHANNELS,
        "posLen": POS_LEN,
        "board": {"width": BOARD_X, "height": BOARD_Y},
        "trunkFinalScale": weights.trunk_final_scale,
        "shapes": shapes,
        "tensors": {k: [float(x) for x in v.reshape(-1)] for k, v in tensors.items()},
        "trunk": [float(x) for x in trunk.reshape(-1)],
        "expected": {
            "headInput": [float(x) for x in head_input.reshape(-1)],
            "policyLogits": [float(x) for x in logits.reshape(-1)],
            "policyPass": float(pass_logit),
            "policyProbs": [float(x) for x in probs.reshape(-1)],
            "ownership": [float(x) for x in ownership.reshape(-1)],
        },
        "reduction": {
            "selected": selected,
            "mode": "only",
            "policyLogits": [float(x) for x in red_logits.reshape(-1)],
            "policyPass": float(red_pass),
            "ownership": [float(x) for x in red_own.reshape(-1)],
        },
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(fixture, indent=1) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
